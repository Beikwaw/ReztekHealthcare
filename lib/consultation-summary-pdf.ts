const NON_CLINICAL_PREFIXES = [
  "this is ai-generated",
  "please review",
  "ai-generated",
  "generated by",
  "assistant",
  "note:",
  "disclaimer",
  "ai assisted",
  "ai-assisted",
  "ai summary",
  "openai",
  "language model",
  "automated summary",
]

/** Remove AI-related phrases from text so the PDF never displays "AI" or similar. */
function stripAiWording(text: string): string {
  if (!text || !text.trim()) return text
  let out = text
  const aiPhrases = [
    /\bAI[- ]?generated\b/gi,
    /\bgenerated by AI\b/gi,
    /\bAI[- ]?assisted\b/gi,
    /\bAI[- ]?summary\b/gi,
    /\bAI[- ]?draft\b/gi,
    /\b\(AI\)\b/gi,
    /\b\[AI\]\b/gi,
    /\bOpenAI\b/gi,
    /\bassistant['\s]*s?\s*:\s*/gi,
    /\bthis (?:content|summary|diagnosis) (?:was )?(?:is )?generated (?:by|with)\b/gi,
    /\bplease review (?:and )?edit\b/gi,
    /\bdisclaimer\s*:.*$/gim,
  ]
  aiPhrases.forEach((re) => {
    out = out.replace(re, "")
  })
  return out.replace(/\n{3,}/g, "\n\n").trim()
}

function stripNonClinicalLines(text: string): string {
  const lines = text.split(/\r?\n/)
  return lines
    .filter((line) => {
      const lower = line.trim().toLowerCase()
      if (!lower) return true
      return !NON_CLINICAL_PREFIXES.some((p) => lower.startsWith(p))
    })
    .join("\n")
}

export function parseSummaryAndDiagnosis(fullText: string): {
  clinicalSummary: string
  diagnosis: string
} {
  const cleaned = stripNonClinicalLines(fullText).trim()
  const diagnosisMatch = cleaned.match(
    /\n\s*(?:DIAGNOSIS\s*\/\s*IMPRESSION|DIAGNOSIS)\s*\n/i
  )
  if (diagnosisMatch && diagnosisMatch.index !== undefined) {
    const clinicalSummary = cleaned.slice(0, diagnosisMatch.index).trim()
    const diagnosis = cleaned.slice(diagnosisMatch.index + diagnosisMatch[0].length).trim()
    return {
      clinicalSummary: clinicalSummary.replace(/^CLINICAL\s+SUMMARY\s*\n?/i, "").trim(),
      diagnosis: diagnosis.replace(/^DIAGNOSIS\s*\/\s*IMPRESSION\s*\n?/i, "").replace(/^DIAGNOSIS\s*\n?/i, "").trim(),
    }
  }
  const diagOnly = cleaned.match(/\n\s*DIAGNOSIS\s*\n/i)
  if (diagOnly && diagOnly.index !== undefined) {
    const clinicalSummary = cleaned.slice(0, diagOnly.index).trim()
    const diagnosis = cleaned.slice(diagOnly.index + diagOnly[0].length).trim()
    return {
      clinicalSummary: clinicalSummary.replace(/^CLINICAL\s+SUMMARY\s*\n?/i, "").trim(),
      diagnosis,
    }
  }
  return {
    clinicalSummary: cleaned.replace(/^CLINICAL\s+SUMMARY\s*\n?/i, "").trim(),
    diagnosis: "",
  }
}

export interface PatientDetailForPdf {
  name: string
  phone?: string
  email?: string
  address?: string
  dateOfBirth?: Date | string
  patientNumber?: string
  /** Optional doctor name for this consultation/script */
  doctorName?: string
}

export interface BillItemForPdf {
  description: string
  amount: number
}

/** Optional consultation sections for PDF: PC, onset, vitals, exam, investigations */
export interface ConsultationExtraForPdf {
  presentingComplaint?: string
  onset?: string
  vitalSigns?: string
  physicalExamination?: string
  specialInvestigations?: string
}

/** Filename for full-page letterhead background (must match exactly) */
const LETTERHEAD_BACKGROUND_FILENAME = "letterhead-full.png"

/**
 * Load full-page letterhead image as base64 for PDF background.
 * Server: reads from public/letterhead-full.png. Client: fetches /letterhead-full.png.
 * Exported for use by medical-aid-claim-pdf so claim PDF matches consultation summary layout.
 */
export async function getLetterheadBackgroundBase64(): Promise<string | null> {
  try {
    if (typeof window === "undefined") {
      const fs = await import("fs")
      const path = await import("path")
      const letterheadPath = path.join(process.cwd(), "public", LETTERHEAD_BACKGROUND_FILENAME)
      if (fs.existsSync(letterheadPath)) {
        const imageBuffer = fs.readFileSync(letterheadPath)
        return `data:image/png;base64,${imageBuffer.toString("base64")}`
      }
      return null
    }
    // Client-side: fetch from public URL
    const res = await fetch(`/${LETTERHEAD_BACKGROUND_FILENAME}`)
    if (!res.ok) return null
    const blob = await res.blob()
    const buffer = await new Promise<ArrayBuffer>((resolve, reject) => {
      const reader = new FileReader()
      reader.onloadend = () => resolve(reader.result as ArrayBuffer)
      reader.onerror = reject
      reader.readAsArrayBuffer(blob)
    })
    const base64 = btoa(
      new Uint8Array(buffer).reduce((data, byte) => data + String.fromCharCode(byte), "")
    )
    return `data:image/png;base64,${base64}`
  } catch (error) {
    console.error("Failed to load letterhead background:", error)
    return null
  }
}

/**
 * Load doctor stamp image as base64 string (works server-side only).
 * Uses dynamic import to avoid client-side errors.
 */
async function getDoctorStampBase64(): Promise<string | null> {
  try {
    if (typeof window === "undefined") {
      const fs = await import("fs")
      const path = await import("path")
      const stampPath = path.join(process.cwd(), "public", "doctor-stamp.png")
      if (fs.existsSync(stampPath)) {
        const imageBuffer = fs.readFileSync(stampPath)
        return `data:image/png;base64,${imageBuffer.toString("base64")}`
      }
    }
    return null
  } catch (error) {
    console.error("Failed to load doctor stamp:", error)
    return null
  }
}

/**
 * Build PDF document with letterhead background (exact image) then patient details, summary, diagnosis.
 * NO BILL SECTION - consultation PDF only contains consultation details.
 * When letterhead image is available it is used as full-page background; content is placed in the content area.
 */
function orNotRecorded(s: string | undefined): string {
  return s && s.trim() ? s.trim() : "Not recorded"
}

async function buildConsultationPdf(
  patient: PatientDetailForPdf,
  primaryText: string,
  secondaryText: string,
  date: Date,
  _billItems?: BillItemForPdf[],
  includeStamp: boolean = false,
  mode: "consultation" | "prescription" = "consultation",
  extra?: ConsultationExtraForPdf
): Promise<jsPDF> {
  const doc = new jsPDF("p", "mm", "a4")
  const margin = 14
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()

  // Load full-page letterhead background (exact match to provided image)
  const letterheadBase64 = await getLetterheadBackgroundBase64()

  let y: number
  if (letterheadBase64) {
    // Full-page background: image matches exactly (header + blank middle + stamp in bottom right)
    doc.addImage(letterheadBase64, "PNG", 0, 0, pageWidth, pageHeight, undefined, "FAST", 0)
    y = 78 + 10 // Content starts below header
  } else {
    // Fallback: draw header when letterhead image not available
    doc.setDrawColor(0, 0, 0)
    doc.setLineWidth(0.5)
    const boxTop = 10
    const boxHeight = 62
    const boxWidth = pageWidth - margin * 2
    doc.rect(margin, boxTop, boxWidth, boxHeight)
    doc.rect(margin + 2, boxTop + 2, boxWidth - 4, boxHeight - 4)
    doc.setFontSize(18)
    doc.setFont("times", "bold")
    doc.text(LETTERHEAD.doctorName, pageWidth / 2, 22, { align: "center" })
    doc.setFontSize(10)
    doc.setFont("times", "normal")
    doc.text(LETTERHEAD.qualifications, pageWidth / 2, 28, { align: "center" })
    doc.text(LETTERHEAD.practiceNumber, pageWidth - margin, 28, { align: "right" })
    const col1 = margin + 5
    const col2 = pageWidth / 2 - 8
    const col3 = pageWidth - margin - 5
    let colY = 36
    doc.setFont("helvetica", "bold")
    doc.setFontSize(9)
    doc.text(LETTERHEAD.surgery.label, col1, colY)
    doc.setFont("helvetica", "normal")
    doc.setFontSize(9)
    doc.text(LETTERHEAD.surgery.address, col1, colY + 5)
    doc.text(LETTERHEAD.surgery.location, col1, colY + 10)
    doc.text(LETTERHEAD.surgery.city, col1, colY + 15)
    doc.text(LETTERHEAD.surgery.telFax, col1, colY + 20)
    doc.setFont("helvetica", "bold")
    doc.text("MAIN PRACTICE", col2, colY)
    doc.setFont("helvetica", "normal")
    doc.text(LETTERHEAD.main.shop, col2, colY + 5)
    doc.text(LETTERHEAD.main.address, col2, colY + 10)
    doc.text(LETTERHEAD.main.city, col2, colY + 15)
    doc.text(LETTERHEAD.main.tel1, col2, colY + 20)
    doc.text(LETTERHEAD.main.tel2, col2, colY + 25)
    doc.setFont("helvetica", "bold")
    doc.text(LETTERHEAD.postal.label, col3, colY, { align: "right" })
    doc.setFont("helvetica", "normal")
    doc.text(LETTERHEAD.postal.poBox, col3, colY + 5, { align: "right" })
    doc.text(LETTERHEAD.postal.city, col3, colY + 10, { align: "right" })
    doc.text(LETTERHEAD.email, col3, colY + 20, { align: "right" })
    doc.setDrawColor(0, 0, 0)
    doc.setLineWidth(0.2)
    doc.line(margin, 78, pageWidth - margin, 78)
    y = 78 + 10
  }

  // ----- Patient Details Section -----
  doc.setFont("helvetica", "bold")
  doc.setFontSize(11)
  doc.text("Patient Details", margin, y)
  y += 6
  doc.setFont("helvetica", "normal")
  doc.setFontSize(10)
  doc.text("Name: " + (patient.name || "—"), margin, y)
  y += 5
  if (patient.patientNumber) {
    doc.text("Patient No: " + patient.patientNumber, margin, y)
    y += 5
  }
  if (patient.phone) {
    doc.text("Tel: " + patient.phone, margin, y)
    y += 5
  }
  if (patient.email) {
    doc.text("E-mail: " + patient.email, margin, y)
    y += 5
  }
  if (patient.address) {
    const addrLines = doc.splitTextToSize("Address: " + patient.address, 170)
    doc.text(addrLines, margin, y)
    y += addrLines.length * 5
  }
  if (patient.dateOfBirth) {
    const dob = patient.dateOfBirth instanceof Date ? patient.dateOfBirth : new Date(patient.dateOfBirth)
    doc.text("Date of birth: " + dob.toLocaleDateString("en-ZA"), margin, y)
    y += 5
  }
  const dateLabel =
    mode === "prescription" ? "Date & time of script: " : "Date & time of consultation: "
  const dateStr = date.toLocaleDateString("en-ZA", {
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
  })
  const timeStr = date.toLocaleTimeString("en-ZA", { hour: "2-digit", minute: "2-digit" })
  doc.text(dateLabel + `${dateStr} at ${timeStr}`, margin, y)
  y += 5
  if (patient.doctorName) {
    doc.text("Doctor: " + patient.doctorName, margin, y)
    y += 7
  } else {
    y += 7
  }

  // ----- Optional consultation details (PC, onset, vitals, exam, investigations) -----
  if (mode === "consultation" && extra) {
    const sections: { title: string; value: string }[] = [
      { title: "Presenting Complaint", value: orNotRecorded(extra.presentingComplaint) },
      { title: "Onset", value: orNotRecorded(extra.onset) },
      { title: "Vital Signs", value: orNotRecorded(extra.vitalSigns) },
      { title: "Physical Examination", value: orNotRecorded(extra.physicalExamination) },
      { title: "Special Investigations", value: orNotRecorded(extra.specialInvestigations) },
    ]
    for (const { title, value } of sections) {
      if (y > pageHeight - 35) {
        doc.addPage()
        y = 20
      }
      doc.setFont("helvetica", "bold")
      doc.setFontSize(10)
      doc.text(title, margin, y)
      y += 5
      doc.setFont("helvetica", "normal")
      doc.setFontSize(9)
      const lines = doc.splitTextToSize(value, pageWidth - 2 * margin)
      doc.text(lines, margin, y)
      y += lines.length * 4 + 6
    }
    y += 4
  }

  // ----- Body Sections -----
  const cleanPrimary = stripAiWording(primaryText || "")
  const cleanSecondary = stripAiWording(secondaryText || "")

  if (mode === "prescription") {
    // Single-section prescription/script layout
    doc.setFont("helvetica", "bold")
    doc.setFontSize(11)
    doc.text("Prescription / Script", margin, y)
    y += 6
    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)
    const scriptLines = doc.splitTextToSize(cleanPrimary || "—", pageWidth - 2 * margin)
    const lineHeight = 5
    const bottomMargin = 20
    let idx = 0
    while (idx < scriptLines.length) {
      const remainingHeight = pageHeight - bottomMargin - y
      const linesThatFit = Math.max(1, Math.floor(remainingHeight / lineHeight))
      const chunk = scriptLines.slice(idx, idx + linesThatFit)
      doc.text(chunk, margin, y)
      y += chunk.length * lineHeight
      idx += chunk.length
      if (idx < scriptLines.length) {
        doc.addPage()
        y = 20
      }
    }
    y += 15
  } else {
    // Consultation layout: clinical summary + diagnosis
    doc.setFont("helvetica", "bold")
    doc.setFontSize(11)
    doc.text("Clinical Summary", margin, y)
    y += 6
    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)
    const summaryLines = doc.splitTextToSize(cleanPrimary || "—", pageWidth - 2 * margin)
    const lineHeight = 5
    const bottomMargin = 20
    let idxSummary = 0
    while (idxSummary < summaryLines.length) {
      const remainingHeight = pageHeight - bottomMargin - y
      const linesThatFit = Math.max(1, Math.floor(remainingHeight / lineHeight))
      const chunk = summaryLines.slice(idxSummary, idxSummary + linesThatFit)
      doc.text(chunk, margin, y)
      y += chunk.length * lineHeight
      idxSummary += chunk.length
      if (idxSummary < summaryLines.length) {
        doc.addPage()
        y = 20
      }
    }
    y += 10

    doc.setFont("helvetica", "bold")
    doc.setFontSize(11)
    doc.text("Dr Diagnosis and Summary", margin, y)
    y += 6
    doc.setFont("helvetica", "normal")
    doc.setFontSize(10)
    const diagLines = doc.splitTextToSize(cleanSecondary || "—", pageWidth - 2 * margin)
    const diagLineHeight = 5
    const bottomMarginDiag = 20
    let idxDiag = 0
    while (idxDiag < diagLines.length) {
      const remainingHeight = pageHeight - bottomMarginDiag - y
      const linesThatFit = Math.max(1, Math.floor(remainingHeight / diagLineHeight))
      const chunk = diagLines.slice(idxDiag, idxDiag + linesThatFit)
      doc.text(chunk, margin, y)
      y += chunk.length * diagLineHeight
      idxDiag += chunk.length
      if (idxDiag < diagLines.length) {
        doc.addPage()
        y = 20
      }
    }
    y += 15
  }

  // Doctor stamp only when not using full letterhead (letterhead image already has stamp in bottom right)
  if (!letterheadBase64 && includeStamp) {
    const stampBase64 = await getDoctorStampBase64()
    if (stampBase64) {
      try {
        const stampWidth = 50
        const stampHeight = 25
        const stampX = (pageWidth - stampWidth) / 2
        const stampY = pageHeight - stampHeight - 15
        doc.addImage(stampBase64, "PNG", stampX, stampY, stampWidth, stampHeight, undefined, "FAST", 0)
      } catch (error) {
        console.error("Failed to add doctor stamp to PDF:", error)
      }
    }
  }
  // Add page numbers to all pages
  const pageCount = doc.getNumberOfPages()
  doc.setFontSize(9)
  for (let i = 1; i <= pageCount; i += 1) {
    doc.setPage(i)
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - margin, pageHeight - 8, { align: "right" })
  }

  return doc
}

/**
 * Generate and download PDF (client). Uses letterhead + patient + optional consultation details + summary + diagnosis.
 * NO BILL - consultation PDF only contains consultation details.
 * Note: Stamp is not included in client-side downloads.
 */
export async function generateConsultationSummaryPdf(
  patient: PatientDetailForPdf,
  clinicalSummary: string,
  diagnosis: string,
  date: Date,
  billItems?: BillItemForPdf[], // Kept for backward compatibility but ignored
  extra?: ConsultationExtraForPdf
): Promise<void> {
  const doc = await buildConsultationPdf(
    patient,
    clinicalSummary,
    diagnosis,
    date,
    billItems,
    false,
    "consultation",
    extra
  )
  const safeName = (patient.name || "Patient").replace(/[^a-zA-Z0-9\s-]/g, "").replace(/\s+/g, "-").slice(0, 40)
  doc.save(`consultation-summary-${safeName}-${date.toISOString().slice(0, 10)}.pdf`)
}

/**
 * Return PDF as ArrayBuffer (for server upload). Same content as download version.
 * NO BILL - consultation PDF only contains consultation details.
 * Includes doctor stamp at bottom (engraved effect).
 */
export async function getConsultationPdfBuffer(
  patient: PatientDetailForPdf,
  clinicalSummary: string,
  diagnosis: string,
  date: Date,
  billItems?: BillItemForPdf[], // Kept for backward compatibility but ignored
  extra?: ConsultationExtraForPdf
): Promise<ArrayBuffer> {
  const doc = await buildConsultationPdf(
    patient,
    clinicalSummary,
    diagnosis,
    date,
    billItems,
    true,
    "consultation",
    extra
  )
  return doc.output("arraybuffer") as ArrayBuffer
}

/**
 * Return a prescription/script PDF as ArrayBuffer for server-side use.
 * Layout matches the consultation PDF (same letterhead and patient details),
 * but the body text is the doctor's prescription script.
 */
export async function getPrescriptionPdfBuffer(
  patient: PatientDetailForPdf,
  scriptText: string,
  date: Date
): Promise<ArrayBuffer> {
  const cleanedScript = stripAiWording(stripNonClinicalLines(scriptText || "")).trim()
  const body = cleanedScript || "Prescription as per doctor's notes."
  const doc = await buildConsultationPdf(patient, body, "", date, undefined, true, "prescription")
  return doc.output("arraybuffer") as ArrayBuffer
}
