/** Get category by id */
export function getCategoryById(id: string): QuestionnaireCategory | undefined {
  return GENERAL_HEALTH_QUESTIONNAIRE.find((c) => c.id === id)
}

/** Flatten selected symptoms from questionnaire format to list of "Category: label" */
export function flattenSelectedSymptoms(
  symptoms: Record<string, Record<string, boolean>>,
  categories: QuestionnaireCategory[] = GENERAL_HEALTH_QUESTIONNAIRE
): string[] {
  const list: string[] = []
  for (const cat of categories) {
    const catData = symptoms[cat.id]
    if (!catData) continue
    for (const item of cat.items) {
      if (catData[item.id]) list.push(`${cat.title}: ${item.label}`)
    }
  }
  return list
}
